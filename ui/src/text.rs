/// The text for the system language: Spanish for any `es*` locale.
pub fn current() -> &'static Text {
    let spanish = ["LC_ALL", "LC_MESSAGES", "LANG"]
        .iter()
        .filter_map(|key| std::env::var(key).ok())
        .find(|value| !value.is_empty())
        .is_some_and(|value| value.starts_with("es"));
    if spanish { &ES } else { &EN }
}
